// Writes supabase/seed.sql (profile "My Wardrobe", default categories, the 31 verified items).
import fs from 'node:fs';
import { SEED_ITEMS, SEED_PROFILE, DEFAULT_CATEGORIES } from '../src/lib/data/seed.ts';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
let sql = '-- Generated by scripts/seed-sql.mjs — idempotent\n';
sql += `insert into public.profiles (id,name,color,avatar_emoji,sort) values (${q(SEED_PROFILE.id)},${q(SEED_PROFILE.name)},${q(SEED_PROFILE.color)},${q(SEED_PROFILE.avatar_emoji)},0) on conflict (id) do nothing;\n`;
sql += 'insert into public.categories (id,name,slot,sort,builtin) values\n' +
  DEFAULT_CATEGORIES.map((c) => `(${q(c.id)},${q(c.name)},${q(c.slot)},${c.sort},true)`).join(',\n') + '\non conflict (id) do nothing;\n';
const cols = ['id','profile_id','name','details','category_id','primary_color','accent_colors','palette_hex','fabric','work','occasions','season','tags','image_url','thumb_url','phash','created_at','updated_at'];
sql += `insert into public.items (${cols.join(',')}) values\n` + SEED_ITEMS.map((i) => '(' + [
  q(i.id), q(i.profile_id), q(i.name), q(i.details), q(i.category_id), q(i.primary_color), arr(i.accent_colors), arr(i.palette_hex),
  q(i.fabric), q(i.work), arr(i.occasions), q(i.season), arr(i.tags), q(i.image_url), q(i.thumb_url), q(i.phash), q(i.created_at), q(i.updated_at),
].join(',') + ')').join(',\n') + '\non conflict (id) do nothing;\n';
fs.writeFileSync('supabase/seed.sql', sql);
console.log('wrote supabase/seed.sql', sql.length, 'bytes');
